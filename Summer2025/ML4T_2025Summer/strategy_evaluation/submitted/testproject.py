"""
--------------------------------------------------------
# testproject.py

This is the main driver script for the ML4T final project. It sequentially runs:

1. Manual Strategy - generates trades based on hardcoded rules
2. Strategy Learner - uses machine learning to generate trades
3. Experiment 1 - compares Manual Strategy vs Strategy Learner
4. Experiment 2 - tests the impact of transaction costs (impact)

Additionally:
- Computes portfolio values using marketsimcode for both strategies.

# OUTPUT:
- No console output or files generated by this script except debug prints

# STEPS:
STEP 1: Import required libraries and modules
STEP 2: Run Manual Strategy on in-sample and out-of-sample data, compute portfolio values
STEP 3: Run Strategy Learner, compute portfolio values
STEP 4: Run Experiment 1
STEP 5: Run Experiment 2
--------------------------------------------------------
"""

# STEP 1: Import necessary libraries and modules
import datetime as dt                    # For handling dates
import ManualStrategy as manual_strat    # Import ManualStrategy
import StrategyLearner as strat_learner  # Import StrategyLearner
import experiment1 as exp_one            # Experiment 1: compare strategies
import experiment2 as exp_two            # Experiment 2: impact analysis
from marketsimcode import compute_portvals  # Import the portfolio simulator

def main():
    symbol = "JPM"
    start_val = 100000
    commission = 9.95
    impact = 0.005

    # Define date ranges
    insample_sd = dt.datetime(2008,1,1)
    insample_ed = dt.datetime(2009,12,31)
    outsample_sd = dt.datetime(2010,1,1)
    outsample_ed = dt.datetime(2011,12,31)

    # STEP 2: Run Manual Strategy
    print("Running Manual Strategy...")
    manual_strategy_instance = manual_strat.ManualStrategy(verbose=False, impact=impact, commission=commission)

    manual_trades_insample = manual_strategy_instance.testPolicy(symbol=symbol, sd=insample_sd, ed=insample_ed, sv=start_val)
    manual_trades_outsample = manual_strategy_instance.testPolicy(symbol=symbol, sd=outsample_sd, ed=outsample_ed, sv=start_val)

    # Compute portfolio values for Manual Strategy
    portvals_manual_insample = compute_portvals(manual_trades_insample, start_val, commission=commission, impact=impact)
    portvals_manual_outsample = compute_portvals(manual_trades_outsample, start_val, commission=commission, impact=impact)

    print("Manual Strategy In-sample Portfolio Values (head):\n", portvals_manual_insample.head())
    print("Manual Strategy Out-of-sample Portfolio Values (head):\n", portvals_manual_outsample.head())

    # STEP 3: Run Strategy Learner
    print("Running Strategy Learner...")
    strategy_learner_instance = strat_learner.StrategyLearner(verbose=False, impact=impact, commission=commission)
    strategy_learner_instance.add_evidence(symbol=symbol, sd=insample_sd, ed=insample_ed, sv=start_val)

    learner_trades_insample = strategy_learner_instance.testPolicy(symbol=symbol, sd=insample_sd, ed=insample_ed, sv=start_val)
    learner_trades_outsample = strategy_learner_instance.testPolicy(symbol=symbol, sd=outsample_sd, ed=outsample_ed, sv=start_val)

    # Compute portfolio values for Strategy Learner
    portvals_learner_insample = compute_portvals(learner_trades_insample, start_val, commission=commission, impact=impact)
    portvals_learner_outsample = compute_portvals(learner_trades_outsample, start_val, commission=commission, impact=impact)

    print("Strategy Learner In-sample Portfolio Values (head):\n", portvals_learner_insample.head())
    print("Strategy Learner Out-of-sample Portfolio Values (head):\n", portvals_learner_outsample.head())

    # STEP 4: Run Experiment 1
    print("Running Experiment 1: Comparing strategies...")
    exp_one.run()

    # STEP 5: Run Experiment 2
    print("Running Experiment 2: Varying impact analysis...")
    exp_two.run()

    print("All tasks completed successfully!")

# Execute main if script is called directly
if __name__ == "__main__":
    main()

