# STEP 1: Import required libraries and modules
import datetime as dt                    # for date handling   
import ManualStrategy as manual_strat    # Import the manual strategy implementation
import StrategyLearner as strat_learner  # Import the strategy learner implementation
import experiment1 as exp_one            # Import the first experiment module    
import experiment2 as exp_two            # Import the second experiment module

# STEP 2: Run Manual Strategy
print("Running Manual Strategy...")
manual_strategy_instance = manual_strat.ManualStrategy(verbose=False, impact=0.005, commission=9.95)

# Generate trades for in-sample data
manual_trades_insample = manual_strategy_instance.testPolicy(symbol="JPM",
                                                             sd=dt.datetime(2008,1,1),
                                                             ed=dt.datetime(2009,12,31),
                                                             sv=100000)

# Generate trades for out-of-sample data
manual_trades_outsample = manual_strategy_instance.testPolicy(symbol="JPM",
                                                              sd=dt.datetime(2010,1,1),
                                                              ed=dt.datetime(2011,12,31),
                                                              sv=100000)

# STEP 3: Run Strategy Learner
print("Running Strategy Learner...")
strategy_learner_instance = strat_learner.StrategyLearner(verbose=False, impact=0.005, commission=9.95)

# Train on in-sample data
strategy_learner_instance.add_evidence(symbol="JPM",
                                       sd=dt.datetime(2008,1,1),
                                       ed=dt.datetime(2009,12,31),
                                       sv=100000)

# Test on in-sample data
learner_trades_insample = strategy_learner_instance.testPolicy(symbol="JPM",
                                                               sd=dt.datetime(2008,1,1),
                                                               ed=dt.datetime(2009,12,31),
                                                               sv=100000)

# Test on out-of-sample data
learner_trades_outsample = strategy_learner_instance.testPolicy(symbol="JPM",
                                                                sd=dt.datetime(2010,1,1),
                                                                ed=dt.datetime(2011,12,31),
                                                                sv=100000)

# STEP 4: Run Experiment 1 - Compare Manual Strategy vs Strategy Learner
print("Running Experiment 1: Comparing strategies...")
exp_one.run()

# STEP 5: Run Experiment 2 - Show effects of varying market impact
print("Running Experiment 2: Varying impact analysis...")
exp_two.run()

print("All tasks completed successfully!")

